"""Generate Go diagnostic snapshots from an explicitly selected Core checkout."""

import argparse
from pathlib import Path
import sys
import types

ROOT = Path(__file__).resolve().parents[1]
HEADER = "// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 Marek Cingel\n"
NOTICE = "Generated by scripts/generate_diagnostic_vocabulary.py; do not edit."


def load_families(source):
    source = source.resolve()
    script = source / "scripts/generate_diagnostic_vocabulary.py"
    if not script.is_file() or not (source / "tlv/include/tlv/diagnostic.h").is_file():
        raise ValueError("Select a Core checkout containing its canonical vocabulary reader and headers")
    # Load the canonical reader without creating bytecode inside the Core checkout.
    module = types.ModuleType("_opentlv_core_vocabulary")
    module.__file__ = str(script)
    exec(compile(script.read_bytes(), str(script), "exec"), module.__dict__)
    module.ROOT = source
    return module.load()


def camel(suffix):
    return "".join(part.capitalize() for part in suffix.split("_"))


def go(families):
    out = [HEADER, "\n", f"// {NOTICE}\n\n", "package opentlv\n\n",
           'import "github.com/OpenTLV/opentlv-go/internal/capi"\n']
    for binding, _, _, _, members in families:
        out.append(f"\n// {binding} identifies a canonical C diagnostic category.\n")
        out.append(f"type {binding} int\n\nconst (\n")
        width = max(len(binding + camel(suffix)) for suffix, _, _ in members)
        for suffix, value, _ in members:
            out.append(f"\t{(binding + camel(suffix)).ljust(width)} {binding} = {value}\n")
        out.append(")\n\n// String returns the canonical C spelling, or \"unknown\".\n")
        out.append(f"func (v {binding}) String() string {{ return capi.{binding}Name(int(v)) }}\n")
    return "".join(out)


def go_test(families):
    out = [HEADER, f"// {NOTICE}\n\n", "package opentlv_test\n\n", "import (\n\t\"fmt\"\n\t\"testing\"\n\n",
           '\ttlv "github.com/OpenTLV/opentlv-go"\n)\n\n',
           "func TestDiagnosticVocabularyMatchesNative(t *testing.T) {\n",
           "\tcases := []struct {\n\t\tvalue fmt.Stringer\n\t\tname  string\n\t}{\n"]
    for binding, _, _, _, members in families:
        for suffix, _, name in members:
            out.append(f"\t\t{{tlv.{binding}{camel(suffix)}, \"{name}\"}},\n")
        beyond = max(value for _, value, _ in members) + 1
        out.append(f"\t\t{{tlv.{binding}({beyond}), \"unknown\"}},\n")
    out.append("\t}\n\tfor _, c := range cases {\n")
    out.append("\t\tif got := c.value.String(); got != c.name {\n")
    out.append("\t\t\tt.Errorf(\"%T(%v): got %q, want %q\", c.value, c.value, got, c.name)\n")
    out.append("\t\t}\n\t}\n}\n")
    return "".join(out)


OUTPUTS = (
    ("diagnostic_kind.go", go),
    ("diagnostic_vocabulary_test.go", go_test),
)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--core-source", type=Path, required=True,
                        help="explicit Core checkout supplying canonical C enums and names")
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args(argv)
    try:
        families = load_families(args.core_source)
    except (ValueError, OSError) as error:
        parser.error(str(error))
    stale = []
    for name, render in OUTPUTS:
        path = ROOT / name
        expected = render(families)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == expected:
            continue
        if args.check:
            stale.append(name)
        else:
            path.write_bytes(expected.encode("utf-8"))
            print(f"updated {path}")
    if stale:
        print("Stale Go diagnostic snapshots: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
